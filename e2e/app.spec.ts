test('markup in names is shown as text', async ({ page }) => {
  const evil = '<img src=x onerror="window.pwned=1">'
  await newClass(page)
  await importFile(page, 's.csv', `Student,Quiz <script>1</script>\nPoints Possible,10\n"${evil.replaceAll('"', '""')}",9\n`)
  await importFile(page, 'm.csv', 'assessment,standard\nQuiz <script>1</script>,7.EE.A.1\n')
  await tab(page, 'Gradebook')
  await expect(page.getByRole('button', { name: evil })).toBeVisible()
  await page.getByRole('link', { name: 'Family reports' }).click()
  await expect(page.getByRole('heading', { name: evil })).toBeVisible()
  expect(await page.evaluate(() => (window as unknown as { pwned?: number }).pwned)).toBeUndefined()
  await expect(row(page, 'nobody')).toHaveCount(0)
})

