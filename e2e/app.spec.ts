import { expect, handClass, importFile, levels, newClass, row, tab, test } from './fixtures'

test('landing demo switches method', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('.demo .heatmap tbody tr')).toHaveCount(12)
  await page.getByRole('radio', { name: 'Mean' }).click()
  await expect(page.getByRole('radio', { name: 'Mean' })).toHaveAttribute('aria-checked', 'true')
  await page.getByRole('link', { name: 'Try the sample class' }).click()
  await expect(page.getByRole('heading', { name: /Grade 7 Math, Period 3/ })).toBeVisible()
})

for (const [id, name, students, standards] of [['grade7', 'Grade 7 Math, Period 3', 28, 10], ['alg1', 'Algebra 1, Block B', 24, 8]] as const) {
  test(`sample ${id}: every tab opens`, async ({ page }) => {
    await page.goto(`/app?sample=${id}`)
    await expect(page.getByRole('heading', { name: new RegExp(name) })).toContainText('Synthetic')
    await expect(page.locator('table.heatmap tbody tr')).toHaveCount(students)
    await expect(page.locator('th.hm-std')).toHaveCount(standards)
    await tab(page, 'Compare methods')
    await expect(page.locator('.method-card')).toHaveCount(7)
    await tab(page, 'Reteach groups')
    await expect(page.locator('.group-card').first()).toBeVisible()
    await tab(page, 'Students')
    await expect(page.locator('.student-list li')).toHaveCount(students)
    await tab(page, 'History')
    await expect(page.getByRole('row', { name: /^Quarter 1/ })).toBeVisible()
    await tab(page, 'Data & setup')
    await expect(page.getByText('This is a synthetic sample, so its data is read-only.')).toBeVisible()
  })
}

test('classes: rename, delete and undo, and everything survives a reload', async ({ page }) => {
  await handClass(page)
  await page.goto('/app')
  await page.getByRole('button', { name: 'Rename' }).click()
  await page.getByLabel('Class name').fill('Period 5 <b>Math</b>')
  await page.getByLabel('Class name').press('Enter')
  await expect(page.getByRole('link', { name: 'Period 5 <b>Math</b>' })).toBeVisible()
  await page.getByRole('button', { name: 'Delete' }).click()
  await page.getByRole('button', { name: 'Delete class' }).click()
  await expect(page.locator('.project-card')).toHaveCount(0)
  await page.getByRole('button', { name: 'Undo' }).click()
  await page.getByRole('link', { name: 'Period 5 <b>Math</b>' }).click()
  expect(await levels(page, 'Ada Okafor')).toEqual(['3', '3', 'A'])
  await page.reload()
  expect(await levels(page, 'Bo Ng')).toEqual(['2', '1', 'F'])
})

test('clearing the gradebook asks first and can be undone', async ({ page }) => {
  await handClass(page)
  await tab(page, 'Data & setup')
  await page.getByRole('button', { name: 'Clear gradebook' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Clear gradebook' }).click()
  await expect(page.getByText('Start here.')).toBeVisible()
  await page.getByRole('button', { name: 'Undo' }).click()
  await expect(page.getByRole('heading', { name: 'Assessments and standards' })).toBeVisible()
  await tab(page, 'Gradebook')
  expect(await levels(page, 'Ada Okafor')).toEqual(['3', '3', 'A'])
})

test('defaults and theme persist and apply to new classes', async ({ page }) => {
  await page.goto('/settings')
  await page.getByLabel('Calculation method').selectOption('mean')
  await page.getByLabel('Proficiency scale').selectOption('3pt')
  await page.getByRole('radio', { name: 'Dark' }).click()
  await page.reload()
  await expect(page.getByLabel('Calculation method')).toHaveValue('mean')
  await expect(page.locator('html')).toHaveAttribute('data-theme-mode', 'dark')
  await newClass(page)
  await importFile(page, 'a.csv', 'Student,Quiz 1\nPoints Possible,10\nAda,9\n')
  await importFile(page, 'm.csv', 'assessment,standard\nQuiz 1,7.EE.A.1\n')
  await tab(page, 'Gradebook')
  await expect(page.getByLabel('Calculation method')).toHaveValue('mean')
  expect((await levels(page, 'Ada'))[0]).toBe('3')
})

